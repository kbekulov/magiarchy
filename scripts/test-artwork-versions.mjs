import assert from 'node:assert/strict';
import { testGalleryFilters } from './test-gallery-filters.mjs';
import { testGalleryIntake } from './test-gallery-intake.mjs';

export async function testArtworkVersions(page, origin, engine) {
  await testGalleryFilters(page, origin, engine);
  await testGalleryIntake(page, origin, engine);
  for (const width of [390, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await page.goto(`${origin}/gallery.html`);
    await page.waitForLoadState('networkidle');
    const only = page.locator('#gallery-chibi-filter');
    const exclude = page.locator('#gallery-exclude-chibi-filter');
    if (width > 1000) {
      const first = await only.locator('..').boundingBox();
      const second = await exclude.locator('..').boundingBox();
      assert.ok(Math.abs(second.x - first.x) < 1 && second.y - first.y - first.height <= 8, 'Related chibi toggles should stay grouped on desktop');
    }
    const visibleCards = page.locator('.gallery-card:not([hidden])');
    const allCount = await visibleCards.count();
    await only.check({ force: true });
    assert.ok(await visibleCards.count() > 0);
    assert.equal(await visibleCards.filter({ has: page.locator('img') }).evaluateAll(cards => cards.every(card => card.dataset.chibi === 'true')), true);
    await exclude.check({ force: true });
    assert.equal(await only.isChecked(), false);
    assert.ok(await visibleCards.count() > 0);
    assert.equal(await visibleCards.evaluateAll(cards => cards.every(card => card.dataset.chibi !== 'true')), true);
    await only.check({ force: true });
    assert.equal(await exclude.isChecked(), false);
    await only.uncheck({ force: true });
    assert.equal(await visibleCards.count(), allCount);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    const historicalCards = page.locator('[data-historical="true"]');
    assert.equal(await historicalCards.count(), 2);
    const historical = historicalCards.first();
    await historical.scrollIntoViewIfNeeded();
    await page.waitForTimeout(250);
    assert.ok(await historical.evaluate(card => {
      const other = [...card.parentElement.children].find(item => item !== card && !item.hidden);
      const tail = [...card.parentElement.children].slice(-2);
      return tail[0] === card && tail.every(item => item.dataset.historical === 'true') && getComputedStyle(card).gridColumnStart === 'auto' && Math.abs(card.getBoundingClientRect().width - other.getBoundingClientRect().width) < 2;
    }), 'Historical artwork must remain last and use the same masonry column width');
    assert.ok((await historical.textContent()).includes('2021 OR EARLIER'));
    assert.equal(await historical.getAttribute('data-character'), '');
    assert.equal(await historical.getAttribute('data-profile-portrait'), 'false');
    assert.ok((await historical.innerText()).includes('no connection to the current characters'));
    await page.screenshot({ path: `test-results/${engine}-historical-masonry-${width}.png` });
    await historical.locator('a').click();
    await page.waitForURL('**/gallery.html?image=author-hand-drawn-sketch-circa-2021');
    assert.equal(await page.locator('#gallery-detail-title').innerText(), 'Earliest cast sketch - Part 1');
    assert.ok((await page.locator('#gallery-detail-type').textContent()).includes('no connection to the current characters'));
    await page.locator('#gallery-detail-image').evaluate(img => img.decode());
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({ path: `test-results/${engine}-historical-artwork-${width}.png` });
    assert.equal(await page.locator('#gallery-detail-source').getAttribute('href'), 'media/gallery/images/history/earliest-cast-sketch-part-1.png');
    assert.equal(await page.locator('#gallery-siblings a').count(), 2);
    await page.locator('#gallery-siblings a').nth(1).click();
    await page.waitForURL('**/gallery.html?image=earliest-cast-sketch-part-2');
    await page.locator('#gallery-detail-image').evaluate(img => img.decode());
    assert.equal(await page.locator('#gallery-detail-image').evaluate(img => img.naturalWidth), 3606);
    assert.equal(await page.locator('#gallery-detail-source').getAttribute('href'), 'media/gallery/images/history/earliest-cast-sketch-part-2.png');
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({ path: `test-results/${engine}-historical-artwork-part-2-${width}.png` });
    await page.goto(`${origin}/characters.html`);
    await page.waitForLoadState('networkidle');
    const kyrien = page.locator('[data-name="Kyrien"]');
    await kyrien.locator('.character-chibi').evaluate(img => img.decode());
    assert.ok((await kyrien.locator('.character-chibi').getAttribute('src')).includes('char-kyrien-arc-1-chibi-beige-jacket'));
    assert.equal(await kyrien.locator('.art-note').textContent(), 'Arc 1 · Chibi');
    await kyrien.scrollIntoViewIfNeeded();
    await page.screenshot({ path: `test-results/${engine}-kyrien-chibi-${width}.png` });
    await page.goto(`${origin}/gallery.html?image=char-kyrien-arc-1-chibi-beige-jacket`);
    await page.locator('#gallery-detail-image').evaluate(img => img.decode());
    assert.equal(await page.locator('#gallery-detail-source').getAttribute('href'), 'media/gallery/images/chibis/char-kyrien-arc-1-chibi-beige-jacket.png');
    await page.goto(`${origin}/gallery.html?image=char-lynleit-2`);
    await page.waitForLoadState('networkidle');
    assert.ok((await page.locator('#gallery-detail-title').innerText()).includes('Arc 0'));
    assert.equal(await page.locator('#gallery-detail-source').getAttribute('href'), 'media/gallery/images/characters/char-lynleit-arc0-1.png');
    await page.goto(`${origin}/gallery.html?image=char-lynleit-arc2-1`);
    await page.waitForLoadState('networkidle');
    assert.ok((await page.locator('#gallery-detail-title').innerText()).includes('Arc 2'));
    await page.goto(`${origin}/character.html?character=lynleit`);
    await page.waitForLoadState('networkidle');
    await page.getByRole('button', { name: /^Portrait \d+, Arc 0$/ }).click();
    assert.ok(await page.getByText('Arc 0', { exact: true }).isVisible());
    await page.goto(`${origin}/gallery.html`);
    await page.waitForLoadState('networkidle');
    assert.ok(await page.locator('[data-image-version-group="sherie-study-01"][data-image-version="v1"]').isHidden());
    assert.ok(await page.locator('[data-image-version-group="sherie-study-01"][data-image-version="v2"]').isVisible());
    await page.goto(`${origin}/gallery.html?image=char-sherie-1`);
    await page.waitForLoadState('networkidle');
    const nav = page.locator('#gallery-image-versions');
    assert.equal(await nav.locator('a').count(), 2);
    assert.ok((await nav.locator('[aria-current]').innerText()).includes('v1'));
    await nav.getByRole('link', { name: 'v2 · Ankle boots · Default', exact: true }).click();
    await page.waitForURL('**/gallery.html?image=char-sherie-1-v2-ankle-boots');
    await page.waitForLoadState('networkidle');
    assert.ok((await nav.locator('[aria-current]').innerText()).includes('v2'));
    assert.equal(await page.locator('#gallery-detail-source').getAttribute('href'), 'media/gallery/images/characters/char-sherie-1-v2-ankle-boots.png');
    assert.ok(await page.locator('#gallery-siblings').isHidden());
    await nav.scrollIntoViewIfNeeded();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({ path: `test-results/${engine}-artwork-versions-${width}.png` });
    await nav.getByRole('link', { name: 'v1 · Original heels', exact: true }).focus();
    await page.keyboard.press('Enter');
    await page.waitForURL('**/gallery.html?image=char-sherie-1');
    assert.equal(await page.locator('#gallery-detail-source').getAttribute('href'), 'media/gallery/images/characters/char-sherie-1.png');
    await page.goto(`${origin}/gallery.html?image=char-sherie_drake-1`);
    await page.waitForLoadState('networkidle');
    assert.ok(await nav.isHidden());
    await page.goto(`${origin}/gallery.html?image=char-drake-sherie-kyrien-lynleit-felix-lineup-sketch-01`);
    await page.waitForLoadState('networkidle');
    const lineup = page.locator('#gallery-detail-image');
    await lineup.evaluate(img => img.decode());
    assert.ok((await lineup.getAttribute('alt')).includes('heeled ankle boots'));
    assert.equal(await lineup.evaluate(img => img.naturalWidth), 1671);
    assert.equal(await lineup.evaluate(img => img.naturalHeight), 941);
    assert.ok(await nav.isHidden());
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({ path: `test-results/${engine}-lineup-${width}.png` });
    await page.goto(`${origin}/gallery.html?image=char-hiyu-yulia-church-interior`);
    await page.locator('#gallery-detail-image').evaluate(img => img.decode());
    assert.equal(await page.locator('#gallery-detail-title').innerText(), 'Hiyu and Yulia');
    assert.equal(await page.locator('#gallery-detail-source').getAttribute('href'), 'media/gallery/images/characters/char-hiyu-yulia-church-interior.png');
    for (const slug of ['hiyu', 'yulia']) {
      await page.goto(`${origin}/character.html?character=${slug}`);
      await page.waitForLoadState('networkidle');
      const thumbnail = page.locator('.profile-art-thumbnails button').filter({ has: page.locator('img[src*="char-hiyu-yulia-church-interior"]') });
      assert.equal(await thumbnail.count(), 1);
      if (await thumbnail.isVisible()) await thumbnail.click();
      const sharedPortrait = page.locator('.profile-portrait-strip img[src*="char-hiyu-yulia-church-interior"]').first();
      await sharedPortrait.evaluate(img => img.decode());
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
      await page.screenshot({ path: `test-results/${engine}-${slug}-shared-artwork-${width}.png` });
    }
  }
  console.log(`${engine}: artwork versions, source links, keyboard switching and responsive layouts passed`);
}
