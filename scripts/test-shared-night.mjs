import assert from 'node:assert/strict';
import fs from 'node:fs';
import { loadContentNotices } from './content-notices.mjs';

export async function testSharedNight(page, origin, engine) {
  const json = file => JSON.parse(fs.readFileSync(file, 'utf8'));
  const registry = loadContentNotices(process.cwd());
  assert.equal(registry.forURL('story.html?chapter=the-shared-night&version=v1').canon, 'side-content');
  assert.equal(registry.forURL('story.html?chapter=the-shared-night&version=v2').canon, 'canon');
  assert.equal(registry.forURL('docs.html?doc=holumn-incidents-and-testimonies#sleepers'), undefined);
  assert.equal(registry.forURL('docs.html?doc=oneiric-confluence').depiction, 'implied');
  const chapter = json('story/index.json').find(r=>r.slug==='the-shared-night');
  assert.equal(chapter.number,'Unplaced Chapter');
  const moment = json('moments/index.json').find(r=>r.slug===chapter.slug);
  const office = json('moments/index.json').find(r=>r.slug==='fionns-office-after-the-rescue');
  assert.equal(office.timelinePhase, null);
  assert.equal(office.contentKind, 'outline');
  assert.ok(office.known.some(t=>t.includes('Natalia herself notified')));
  const anima = json('gallery/panels.json').find(r=>r.id==='anima-meets-female-cast');
  assert.equal(anima.nonCanon, true);
  assert.equal(anima.panels.filter(panel => !panel.supersededBy).length, 13);
  assert.equal(anima.panels.filter(panel => panel.supersededBy).length, anima.panels.filter(panel => panel.revisionOf).length);
  assert.equal(chapter.timelinePhase, null); assert.equal(moment.timelinePhase,null);
  assert.equal(moment.characters.length,6);
  assert.equal(chapter.defaultVersion, 'v2');
  assert.equal(moment.chapterVersion, 'v2');
  assert.ok(!moment.characters.some(c => ['hiyu', 'yulia'].includes(c.slug)));
  const text=fs.readFileSync('story/'+chapter.file,'utf8');
  for (const wording of ['The mask belongs to you too.', 'A capacity revealed is not necessarily an intention confessed.', 'You made it sound like plumbing.', 'COFFEE. 10.', 'Sherie stepped sideways.', '[WRITER:']) assert.ok(text.includes(wording),wording);
  assert.ok(!/She kissed him|She had kissed Felix|Hiyu|Yulia/.test(text));
  assert.ok(!text.includes('linked in real time'));
  assert.ok(text.length>30000,'Preserve substantial author prose outside the corrected beats');
  const visit = async url => { await page.goto(`${origin}/${url}`); await page.waitForLoadState('networkidle'); };
  for (const width of [1280,390]) {
    await page.setViewportSize({width,height:900});
    await visit('story.html');
    const card=page.locator('.document-card').filter({has:page.locator('a[href="story.html?chapter=the-shared-night"]')});
    assert.equal(await card.isVisible(),false);
    const controls=page.getByRole('group',{name:'H Scene visibility',exact:true});
    await controls.getByRole('switch',{name:'Include H Scenes',exact:true}).check();
    assert.ok(await card.isVisible());
    await controls.getByRole('switch',{name:'H Scenes only',exact:true}).check();
    assert.equal(await controls.getByRole('switch',{name:'Include H Scenes',exact:true}).isChecked(),false);
    await page.getByRole('button',{name:'Scene outline',exact:true}).click();
    assert.equal(await card.isVisible(),false);
    await page.getByRole('button',{name:'All Chapters',exact:true}).click();
    await card.locator('a').click(); await page.waitForLoadState('networkidle');
    assert.ok(await page.locator('#chapter-reader-view .content-notice-full').isVisible());
    assert.match(await page.locator('#chapter-reader-view .content-notice-full').textContent(),/Explicit sexual language; sexual acts off-page/);
    assert.equal(await page.locator('.story-timeline .is-active').count(),0);
    assert.ok(await page.locator('#chapter-reader').textContent().then(t=>t.includes('Sherie stepped sideways.')));
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await page.locator('#chapter-reader-view .content-notice-full').scrollIntoViewIfNeeded();
    await page.screenshot({path:`test-results/${engine}-shared-night-${width}.png`});
    await visit('moments.html');
    const momentCard=page.locator('.moment-card').filter({has:page.locator('a[href="moments.html?moment=the-shared-night"]')});
    assert.equal(await momentCard.isVisible(),false);
    await page.getByRole('switch',{name:'Include H Scenes',exact:true}).check();
    assert.ok(await momentCard.isVisible());
    await momentCard.locator('a').click(); await page.waitForLoadState('networkidle');
    assert.ok(await page.locator('.content-notice-full').isVisible());
    await visit('holumns.html');
    assert.equal(await page.locator('[data-incident="HI-009"]').isVisible(),false);
    await page.getByRole('switch',{name:'Include H Scenes',exact:true}).check();
    assert.ok(await page.locator('[data-incident="HI-009"]').isVisible());
    await page.locator('[data-incident="HI-009"]').scrollIntoViewIfNeeded();
    await page.screenshot({path:`test-results/${engine}-holumn-notices-${width}.png`});
    await visit('docs.html?doc=oneiric-confluence');
    assert.ok(await page.locator('#document-reader .content-notice-full').isVisible());
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await visit('moments.html?moment=fionns-office-after-the-rescue');
    assert.ok((await page.locator('.moment-reader').innerText()).includes('Natalia herself notified'));
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await visit('gallery.html?panels=anima-meets-female-cast#panel-10');
    const panel = page.locator('#panel-10');
    assert.ok(await panel.isVisible());
    await panel.locator('img').evaluate(img=>img.decode());
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await panel.scrollIntoViewIfNeeded();
    await page.screenshot({path:`test-results/${engine}-anima-new-study-${width}.png`});
  }
  await visit('story.html?chapter=the-shared-night&version=v1');
  assert.ok((await page.locator('#chapter-reader').innerText()).includes('She had kissed Felix anyway.'));
  assert.ok((await page.locator('#chapter-reader-view .content-notice-full').innerText()).includes('Superseded'));
  const supplied = anima.panels.find(p=>p.id==='panel-10');
  const imageResponse = await page.request.get(`${origin}/${supplied.src}`);
  assert.deepEqual(await imageResponse.body(), fs.readFileSync(supplied.src));
  await visit('docs.html?doc=character-intimacy-and-sexuality&version=v20');
  assert.ok(!(await page.locator('#document-reader').textContent()).includes('The main events of The Shared Night'));
  await visit('docs.html?doc=character-intimacy-and-sexuality');
  assert.ok((await page.locator('#document-reader').textContent()).includes('The main events of The Shared Night'));
  await visit('index.html');
  await page.getByRole('button',{name:'Search archive',exact:true}).click();
  await page.locator('.global-search-field input').fill('oneiric');
  await page.waitForFunction(()=>!document.querySelector('#global-search-status').textContent.includes('Loading'));
  assert.equal(await page.locator('.global-search-result[href^="docs.html?doc=oneiric-confluence"]').count(),0);
  await page.getByRole('group',{name:'Search H Scene visibility'}).getByRole('switch',{name:'Include H Scenes',exact:true}).check();
  assert.ok(await page.locator('.global-search-result[href^="docs.html?doc=oneiric-confluence"]').count()>0);
  assert.ok(!json('home-dashboard.json').moments.some(r=>r.id==='the-shared-night'));
  console.log(`${engine}: Shared Night canon, notices, filters, mobile layout and history isolation passed.`);
}
